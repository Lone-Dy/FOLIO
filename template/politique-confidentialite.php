        <p>Nous ne vendons jamais vos données personnelles à des tiers.</p>
        <p>Les seules personnes voyant vos données sont :</p>
        <ol>
            <li>Les visiteurs du site (uniquement les informations que vous choisissez de rendre publiques sur votre portfolio).</li>
            <li>Nos prestataires techniques (hébergeurs), uniquement pour le stockage.</li>
        </ol>
