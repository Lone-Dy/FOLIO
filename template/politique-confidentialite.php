        <ol>
            <li>Localisation : Vos données sont hébergées sur des serveurs sécurisés</li>
            <li>Sécurité des fichiers : Les images que vous téléchargez sont traitées avec soin. Nous utilisons des protocoles de sécurité pour empêcher tout accès non autorisé à votre base de données BLOB.</li>
            <li>Mots de passe : Vos mots de passe ne sont jamais stockés en clair. Ils sont cryptés avec des algorithmes de hachage modernes (password_hash).</li>
        </ol>
